"""Assemble the single-file Kaggle kernel from src/ + kernel/train.py.

Only `code_file` is uploaded, so everything has to be inline — this pastes the
model and corpus sources above the training driver so there is one source of
truth per component. edit src/*.py, then rerun this.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

HEADER = '''"""Kaggle CPU dev-loop kernel for H-Net.

Stream a slice of the HQ corpora, train 200 steps on CPU, print the health curve.
CPU sessions do not draw on GPU quota, so this whole path costs nothing but push
latency. Generated by kernel/build_kernel.py from src/ — edit those, not this.
"""

'''

model_body = re.sub(r'^""".*?"""\n', "",
                    open(os.path.join(ROOT, "src", "model.py")).read(), flags=re.S)
corpus_body = re.sub(r'^""".*?"""\n', "",
                     open(os.path.join(ROOT, "src", "corpus.py")).read(), flags=re.S)
train_body = open(os.path.join(ROOT, "kernel", "train.py")).read()

# the preamble owns the imports; strip the duplicated import lines
corpus_body = re.sub(r"^import io\n(?:import .*\n|\n)*?import pyarrow.parquet as pq\n",
                     "", corpus_body, flags=re.S)
train_body = train_body.split("# ==== TRAIN ====\n", 1)[1]

out = HEADER + "# ==== PREAMBLE ====\n" + train_body.split("# ==== TRAIN ====")[0]
out = (HEADER + open(os.path.join(ROOT, "kernel", "train.py")).read()
       .split("# ==== TRAIN ====\n")[0] + "\n" + model_body + "\n" + corpus_body
       + train_body)
open(os.path.join(ROOT, "kernel", "main.py"), "w").write(out)
print(f"wrote kernel/main.py ({len(out)} bytes)")
