"""Build the gate kernel: inline src/model.py + src/flops.py + tests/test_gates.py."""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kernel_gates")
os.makedirs(OUT, exist_ok=True)


def strip_doc(s):
    return re.sub(r'^""".*?"""\n', "", s, flags=re.S)


model = strip_doc(open(os.path.join(ROOT, "src", "model.py")).read())
flops = strip_doc(open(os.path.join(ROOT, "src", "flops.py")).read())
tests = open(os.path.join(ROOT, "tests", "test_gates.py")).read()

tests = tests.replace('sys.path.insert(0, "/home/ikaaros/Coding/kaggle/hnet/src")\n', "")
tests = re.sub(r"^from model import \(.*?\)\n", "", tests, flags=re.S | re.M)
tests = tests.replace("from model import ChunkLayer", "")
tests = tests.replace("    sys.path.insert(0, \"/home/ikaaros/Coding/kaggle/hnet/src\")\n"
                      "    from flops import flops_per_byte\n", "")
tests = tests.replace("from flops import flops_per_byte", "")
tests = tests.split('if __name__ == "__main__":')[0]

head = '''"""Correctness gates, run inside a Kaggle CPU kernel.

The reference implementation needs compiled extensions that will not build for sm_75,
so the reference-diff gate is replaced by an independent second implementation of the
router and the dechunk EMA. Generated by kernel_gates/build.py.
"""

import math
import sys

import torch
import torch.nn.functional as F

'''

tail = '''

if __name__ == "__main__":
    print(f"{len(FAILED)} failing gate(s)")
    for f in FAILED:
        print("  -", f)
    raise SystemExit(1 if FAILED else 0)
'''

open(os.path.join(OUT, "main.py"), "w").write(head + model + "\n" + flops + "\n" + tests + tail)
json.dump({"id": "mauricew/hnet-gates", "title": "hnet gates", "code_file": "main.py",
           "language": "python", "kernel_type": "script", "is_private": True,
           "enable_gpu": False, "enable_tpu": False, "enable_internet": False,
           "keywords": [], "dataset_sources": [], "kernel_sources": [],
           "competition_sources": [], "model_sources": []},
          open(os.path.join(OUT, "kernel-metadata.json"), "w"), indent=2)
print("wrote", OUT)
